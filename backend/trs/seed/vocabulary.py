"""Vocabulary for the demonstration dataset.

What is real and what is not — read this before interpreting anything
----------------------------------------------------------------------
**Real**: the gene symbols, target classes, indication names and therapeutic-
area assignments below. These are public biomedical vocabulary — ``KRAS`` is a
real gene and "metastatic pancreatic adenocarcinoma" is a real disease. Using
real vocabulary is deliberate: an ontology populated with invented gene names
could not be swapped for a live Open Targets or ChEMBL feed, and the point of
the demonstration data is that replacing it is a data problem, not a rewrite.

**Not real**: every sponsor, every program, every compound, every experiment,
every effect size, every development outcome. Sponsors are named after
mountain ranges and rivers precisely so they cannot be confused with real
companies, and every program code is prefixed ``DEMO-``.

**The consequence, stated plainly**: this dataset pairs real target and disease
names with simulated outcomes. A row saying a ``DEMO-`` program against a real
target failed in Phase II is a statement about a random number generator, not
about that target. Every such record carries ``is_synthetic = True``, which
propagates into feature snapshots, model artifacts, scores and the API, and the
interface refuses to present any of it as a validated estimate.
"""

